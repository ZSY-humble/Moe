# 隔离 ROS 2 的 Python 3.10 路径和旧 CUDA 库，仅影响本 Conda 环境。
export _GO2_RL_PYTHONPATH_SET="${PYTHONPATH+x}"
export _GO2_RL_PYTHONPATH="${PYTHONPATH-}"
export _GO2_RL_LIBRARY_PATH_SET="${LD_LIBRARY_PATH+x}"
export _GO2_RL_LIBRARY_PATH="${LD_LIBRARY_PATH-}"
export _GO2_RL_USER_SITE_SET="${PYTHONNOUSERSITE+x}"
export _GO2_RL_USER_SITE="${PYTHONNOUSERSITE-}"
unset PYTHONPATH LD_LIBRARY_PATH
export PYTHONNOUSERSITE=1
